def parse(session):
    """Return {question_no: {'A': 'A', 'B': 'D', ...}} for one session."""
    table = {}
    for line in RAW[session].strip().splitlines():
        parts = line.split()
        if not parts:
            continue
        qno = int(parts[0])
        letters = parts[1:]
        assert len(letters) == 4, (session, line)
        table[qno] = dict(zip("ABCD", letters))
    assert sorted(table) == list(range(1, 101)), session
    return table


def series(session, series_letter):
    table = parse(session)
    return [table[i][series_letter] for i in range(1, 101)]
